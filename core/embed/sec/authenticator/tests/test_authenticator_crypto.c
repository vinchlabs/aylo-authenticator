#include <assert.h>
#include <sec/authenticator.h>
#include <stdio.h>
#include <string.h>
#include "ecdsa.h"
#include "ed25519-donna/ed25519.h"
#include "nist256p1.h"
#include "sha2.h"
#include "test_backend.h"
